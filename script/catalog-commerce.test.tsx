import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {buildCategoryTree,isProductInCategory,findCategoryNameBySlug,getCategorySlug} from '../shared/catalog';
import {PriceDisplay,comparePrices} from '../shared/PriceDisplay';
import {resolveDelivery} from '../shared/delivery';
const require=createRequire(import.meta.url);
const {shippingForDelivery}=require('../admin-floreria/api/src/services/deliveryPolicy');
const {quoteStorefrontOrder}=require('../admin-floreria/api/src/services/storefrontQuote');

const categories=['Computadoras › Laptops','Computadoras › Monitores','Audio › Audífonos','Computadoras'];
const tree=buildCategoryTree(categories);
assert.equal(tree.length,2);assert.equal(tree.find(root=>root.name==='Computadoras')?.children.length,2);
assert.equal(isProductInCategory('Computadoras › Laptops','Computadoras'),true);
assert.equal(isProductInCategory('Computadoras › Monitores','Computadoras › Laptops'),false);
assert.equal(isProductInCategory('Audio › Audífonos','AUDIO'),true);
assert.equal(findCategoryNameBySlug(['Computadoras › Laptops'],'computadoras'),'Computadoras');
assert.notEqual(getCategorySlug('Computadoras › Accesorios'),getCategorySlug('Audio › Accesorios'));
const offer=renderToStaticMarkup(<PriceDisplay price="$80.00" originalPrice="$100.00"/>);
assert.match(offer,/Antes/);assert.match(offer,/Ahora/);assert.match(offer,/<del>\$100.00<\/del>/);assert.match(offer,/−20%/);
assert.equal(comparePrices('$100.00','$90.00').active,false);
assert.doesNotMatch(renderToStaticMarkup(<PriceDisplay price="$80.00"/>),/Antes|Ahora|<del>/);
const rates=[{sector:'Urdesa',cost:5},{sector:'Centro',cost:3}];
assert.equal(resolveDelivery('Guayaquil','Urdesa',rates).cost,0);
assert.equal(shippingForDelivery({deliveryCity:'GUAYAQUIL',sector:'Urdesa',shippingCost:999},rates),0);
assert.equal(resolveDelivery('Daule','Centro',rates).cost,3);
assert.equal(shippingForDelivery({deliveryCity:'Daule',sector:'Centro'},rates),3);
assert.equal(resolveDelivery('Daule','Sin cobertura',rates).isAvailable,false);
assert.throws(()=>shippingForDelivery({deliveryCity:'Daule',sector:'Sin cobertura'},rates),/cobertura/);
assert.throws(()=>shippingForDelivery({deliveryCity:'Daule',sector:'Centro'},[{sector:'Centro',cost:null}]),/configurado/);
assert.equal(shippingForDelivery({sector:'Urdesa'},rates),5,'Legacy quotes retain their configured fee');
const db={company:{findMany:async()=>[{id:'fixture',settings:{paymentSettings:{shippingSectorRates:rates}}}]},product:{findMany:async()=>[{id:'p',name:'Fixture',price:80,stock:2,hasVariants:false,variants:[],discounts_products:[]}]}};
const quote=await quoteStorefrontOrder(db,{deliveryCity:'Guayaquil',sector:'Urdesa',shippingCost:999,items:[{productId:'p',quantity:1}]});
assert.equal(quote.shipping,0);assert.equal(quote.total,80);
console.log('PASS: category/subcategory navigation, real before/after pricing, free Guayaquil delivery enforced by server, outside coverage and legacy quotes. No real database used.');
